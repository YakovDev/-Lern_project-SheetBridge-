"""
Модель данных транзакции.

Каждая транзакция представляет собой словарь (dict) со следующими обязательными ключами:

Поля:
    date (str): Дата операции в формате "YYYY-MM-DD". Пример: "2021-12-31".
    amount (float): Сумма операции в рублях.
                     Отрицательное значение (-) означает расход.
                     Положительное значение (+) означает доход.
    description (str): Назначение платежа или описание. Пример: "Колхоз".
    category (str): Категория транзакции. Пример: "Супермаркеты".
                    Если категория неизвестна, используется "Неизвестно".
    card_number (str): Последние 4 цифры номера карты.
                       Если карта не указана, возвращается пустая строка "".

Пример валидной транзакции:
    {
        "date": "2021-12-31",
        "amount": -160.89,
        "description": "Колхоз",
        "category": "Супермаркеты",
        "card_number": "7197"
    }

Пример транзакции без карты:
    {
        "date": "2021-12-31",
        "amount": -800.0,
        "description": "Константин Л.",
        "category": "Переводы",
        "card_number": ""
    }
"""

# Можно добавить константу со списком обязательных ключей для валидации,
# но это не обязательно, так как проверки делаются в сервисах.
REQUIRED_FIELDS = ["date", "amount", "description", "category", "card_number"]